const CACHE_PREFIX = "mama-games-";
const CACHE_NAME = `${CACHE_PREFIX}v2`;
const CORE_ASSETS = [
  "/games/",
  "/games/index.html",
  "/games/app.js",
  "/games/manifest.webmanifest",
  "/games/icons/games-icon.svg",
  "/games/icons/favicon-32.png",
  "/games/icons/apple-touch-icon.png",
  "/assets/mama-home-tab.css"
];

self.addEventListener("install", function (event) {
  event.waitUntil(
    caches.open(CACHE_NAME).then(function (cache) {
      return cache.addAll(CORE_ASSETS);
    }).then(function () {
      return self.skipWaiting();
    })
  );
});

self.addEventListener("activate", function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.map(function (key) {
        if (key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME) return caches.delete(key);
        return undefined;
      }));
    }).then(function () {
      return self.clients.claim();
    })
  );
});

self.addEventListener("fetch", function (event) {
  if (event.request.method !== "GET") return;

  const url = new URL(event.request.url);
  if (url.origin !== location.origin || !url.pathname.startsWith("/games/")) return;

  if (event.request.mode === "navigate") {
    // Always fetch game pages fresh (bypass the HTTP cache); fall back to cache offline.
    event.respondWith(
      fetch(event.request, { cache: "no-store" }).then(function (response) {
        const copy = response.clone();
        caches.open(CACHE_NAME).then(function (cache) {
          cache.put(event.request, copy);
        });
        return response;
      }).catch(function () {
        return caches.match(event.request).then(function (cached) {
          return cached || caches.match("/games/");
        });
      })
    );
    return;
  }

  event.respondWith(
    caches.match(event.request).then(function (cached) {
      return cached || fetch(event.request).then(function (response) {
        const copy = response.clone();
        caches.open(CACHE_NAME).then(function (cache) {
          cache.put(event.request, copy);
        });
        return response;
      });
    })
  );
});
